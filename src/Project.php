<?php

declare(strict_types=1);

namespace SharpPhp;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;
use SharpPhp\CodeGen\Emitter;
use SharpPhp\Compiler\CompilationFailed;
use SharpPhp\Compiler\Compiler;
use SharpPhp\Compiler\SourceFile;
use SharpPhp\Runtime\Host;
use SharpPhp\Runtime\Loader;

/**
 * A SharpPHP project: .sphp sources compiled into a build directory.
 *
 * Configuration (optional) lives in the project's composer.json:
 *
 *   "extra": { "sharp": { "source": "src", "output": "var/sharp" } }
 *
 * Builds are cached: sources are recompiled only when a file (or the compiler) changes.
 */
final class Project
{
    /** @var array<string, string> class (lowercase) => source file, after autoload() */
    private array $loaded = [];

    public const DEFAULT_SOURCE = 'src';
    public const DEFAULT_OUTPUT = 'var/sharp';

    public function __construct(
        public readonly string $root,
        public readonly string $sourceDir,
        public readonly string $buildDir,
    ) {
    }

    /** Defaults in a Laravel app: .sphp files next to the PHP classes, the build with Laravel's own caches. */
    public const LARAVEL_SOURCE = 'app';
    public const LARAVEL_OUTPUT = 'storage/framework/sharp';

    /**
     * The project in $root, configured by "extra.sharp" in its composer.json. Without that, sources are
     * in $defaultSource and the build goes to $defaultOutput (relative to $root); in a Laravel app
     * (artisan and app/ in $root) the defaults are app/ and storage/framework/sharp.
     */
    public static function fromDirectory(string $root, ?string $defaultSource = null, ?string $defaultOutput = null): self
    {
        $isLaravel = is_file(rtrim($root, '/\\') . '/artisan') && is_dir(rtrim($root, '/\\') . '/app');
        $defaultSource ??= $isLaravel ? self::LARAVEL_SOURCE : self::DEFAULT_SOURCE;
        $defaultOutput ??= $isLaravel ? self::LARAVEL_OUTPUT : self::DEFAULT_OUTPUT;
        $root = Paths::normalize(rtrim(realpath($root) ?: $root, '/\\'));
        $config = [];
        $composer = $root . '/composer.json';
        if (is_file($composer)) {
            $json = json_decode((string) file_get_contents($composer), true);
            $extra = is_array($json) && is_array($json['extra'] ?? null) ? $json['extra'] : [];
            $config = is_array($extra['sharp'] ?? null) ? $extra['sharp'] : [];
        }
        $source = is_string($config['source'] ?? null) ? $config['source'] : $defaultSource;
        $output = is_string($config['output'] ?? null) ? $config['output'] : $defaultOutput;

        return new self($root, $root . '/' . trim($source, '/'), $root . '/' . trim($output, '/'));
    }

    /**
     * Compiles the project if needed and returns the build manifest.
     *
     * @return array{version: string, fingerprint: string, entry: ?string, classmap: array<string, string>, sourcemap: array<string, array{source: string, lines: array<int, int>}>}
     * @throws CompilationFailed
     */
    public function build(bool $force = false): array
    {
        $sources = Compiler::findSources($this->sourceDir);
        $fingerprint = $this->fingerprint(array_map(static fn (SourceFile $f): string => $f->path, $sources));
        $manifestFile = $this->buildDir . '/manifest.php';

        if (!$force && is_file($manifestFile)) {
            $manifest = include $manifestFile;
            if (is_array($manifest) && ($manifest['fingerprint'] ?? null) === $fingerprint) {
                /** @var array{version: string, fingerprint: string, entry: ?string, classmap: array<string, string>, sourcemap: array<string, array{source: string, lines: array<int, int>}>} $manifest written by build() */
                return $manifest;
            }
        }

        $result = (new Compiler())->compile($sources);

        $classesDir = $this->buildDir . '/classes';
        self::removeDirectory($classesDir);

        $classmap = [];
        $sourcemap = [];
        foreach ($result->files as $file) {
            $relative = 'classes/' . self::relativePath($file->sourcePath, $this->sourceDir);
            $relative = preg_replace('/\.' . Compiler::EXTENSION . '$/i', ($file->part !== '' ? '.' . $file->part : '') . '.php', $relative) ?? $relative;
            self::write($this->buildDir . '/' . $relative, $file->code);
            foreach ($file->classes as $class) {
                $classmap[strtolower($class)] = $relative;
            }
            $sourcemap[$relative] = ['source' => $file->sourcePath, 'lines' => $file->lineMap];
        }

        $manifest = [
            'version' => Emitter::VERSION,
            'fingerprint' => $fingerprint,
            'entry' => $result->entryPoint,
            'classmap' => $classmap,
            'sourcemap' => $sourcemap,
        ];
        self::write($manifestFile, "<?php\n\n// Generated by SharpPHP. Do not edit.\n\nreturn " . var_export($manifest, true) . ";\n");
        // The build is generated: keep it out of git wherever it is (storage/framework/sharp in Laravel).
        if (!is_file($this->buildDir . '/.gitignore')) {
            self::write($this->buildDir . '/.gitignore', "*\n");
        }

        return $manifest;
    }

    /**
     * Builds (if needed) and runs the program's Main method. Returns the exit code.
     *
     * @param list<string> $args
     */
    public function run(array $args = []): int
    {
        try {
            $manifest = $this->build();
        } catch (CompilationFailed $e) {
            Host::fail($e->render($this->root));

            return 1;
        }

        return Host::run($manifest, $this->buildDir, $args, $this->root);
    }

    /**
     * Builds the project if needed and makes its classes loadable, for PHP code that uses classes
     * written in SharpPHP (a Laravel app, a script) without running Main:
     *
     *   require 'vendor/autoload.php';
     *   SharpPhp\Project::fromDirectory(__DIR__)->autoload();
     *   echo App\Pricing::Total([...], 'AM');
     *
     * With $checkSources false an existing build is used as it is, without looking at the sources
     * (production, after "sharp build"); it is built only when there is none.
     *
     * @throws CompilationFailed
     */
    public function autoload(bool $checkSources = true): self
    {
        $manifest = null;
        $manifestFile = $this->buildDir . '/manifest.php';
        if (!$checkSources && is_file($manifestFile)) {
            $manifest = include $manifestFile;
        }
        if (!is_array($manifest) || !is_array($manifest['classmap'] ?? null)) {
            $manifest = $this->build();
        }
        /** @var array<string, string> $classmap */
        $classmap = $manifest['classmap'];
        Loader::register($classmap, $this->buildDir);
        $sources = [];
        $sourcemap = is_array($manifest['sourcemap'] ?? null) ? $manifest['sourcemap'] : [];
        foreach ($classmap as $class => $file) {
            $entry = $sourcemap[$file] ?? null;
            $source = is_array($entry) ? ($entry['source'] ?? null) : null;
            $sources[$class] = is_string($source) ? $source : $file;
        }
        $this->loaded = $sources;

        return $this;
    }

    /**
     * The classes autoload() made loadable (lowercase names, as PHP compares them) and the .sphp file
     * each comes from.
     *
     * @return array<string, string>
     */
    public function loadedClasses(): array
    {
        return $this->loaded;
    }

    public function clean(): void
    {
        self::removeDirectory($this->buildDir);
    }

    /** @param list<string> $sourcePaths */
    private function fingerprint(array $sourcePaths): string
    {
        $parts = [Emitter::VERSION, self::compilerStamp()];
        foreach ($sourcePaths as $path) {
            $parts[] = self::relativePath($path, $this->sourceDir) . ':' . sha1_file($path);
        }

        return sha1(implode("\n", $parts));
    }

    /** Changes whenever the compiler itself changes (useful while developing it). */
    private static function compilerStamp(): string
    {
        /** @var string|null $stamp */
        static $stamp = null;
        if ($stamp === null) {
            $latest = 0;
            $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator(__DIR__, FilesystemIterator::SKIP_DOTS));
            foreach ($iterator as $file) {
                if ($file instanceof \SplFileInfo) {
                    $latest = max($latest, (int) $file->getMTime());
                }
            }
            $stamp = (string) $latest;
        }

        return $stamp;
    }

    /** "Models/User.sphp" for a source in src/Models; just the file name for one outside $base. */
    private static function relativePath(string $path, string $base): string
    {
        return Paths::relative($path, $base) ?? basename($path);
    }

    private static function write(string $path, string $contents): void
    {
        $dir = dirname($path);
        if (!is_dir($dir) && !mkdir($dir, 0777, true) && !is_dir($dir)) {
            throw new RuntimeException("Cannot create directory: $dir");
        }
        $temp = $path . '.' . getmypid() . '.tmp';
        if (file_put_contents($temp, $contents) === false || !rename($temp, $path)) {
            throw new RuntimeException("Cannot write file: $path");
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
    }

    private static function removeDirectory(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        $iterator = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $file) {
            if ($file instanceof \SplFileInfo) {
                $file->isDir() ? rmdir($file->getPathname()) : unlink($file->getPathname());
            }
        }
        rmdir($dir);
    }
}
